import { test } from 'vitest';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = path => fs.readFileSync(path, 'utf8');
const handlers = () => read('src-tauri/src/lib.rs').match(/generate_handler!\[([\s\S]*?)\]/)[1].split(',').map(value => value.trim().split('::').at(-1)).filter(Boolean).sort();
const expectedPlugins = ['core:default', 'core:event:default', 'deep-link:default', 'notification:default', 'updater:allow-check', 'updater:allow-download-and-install'];
test('all 50 registered commands receive explicit main-only application permissions', () => {
  // Given the actual invoke-handler registry and main capability.
  const commands = handlers();
  const capability = JSON.parse(read('src-tauri/capabilities/main-commands.json'));
  const pluginCapability = JSON.parse(read('src-tauri/capabilities/default.json'));
  const build = read('src-tauri/build.rs');
  // When the explicit manifest and permission set are read.
  const manifest = [...build.matchAll(/^    "([a-z_]+)",$/gm)].map(match => match[1]).sort();
  const permissionSet = read('src-tauri/permissions/main-commands.toml');
  const grants = [...permissionSet.matchAll(/"allow-([a-z-]+)"/g)].map(match => match[1].replaceAll('-', '_')).sort();
  // Then every command is granted exactly once, only to main, preserving plugins.
  assert.equal(commands.length, 50);
  assert.deepEqual(manifest, commands);
  assert.deepEqual(grants, commands);
  assert.equal(capability.windows, undefined);
  assert.deepEqual(capability.webviews, ['main']);
  assert.equal(capability.local, true);
  assert.equal(capability.remote, undefined);
  assert.deepEqual(capability.permissions, ['main-commands']);
  assert.deepEqual(pluginCapability.windows, ['main']);
  assert.deepEqual(pluginCapability.permissions, expectedPlugins);
  assert.ok(build.includes('AppManifest::new().commands(APP_COMMANDS)'));
  assert.ok(build.includes('.app_manifest('));
  assert.equal(permissionSet.includes('*'), false);
});
test.skipIf(process.env.BOGUNON_VERIFY_GENERATED_ACL !== '1')('compiled Tauri ACL resolves every custom command for the main capability', () => {
  // Given a successful cargo build using the locked Tauri dependency graph.
  const commands = handlers();
  const manifests = JSON.parse(read('src-tauri/gen/schemas/acl-manifests.json'));
  const capabilities = JSON.parse(read('src-tauri/gen/schemas/capabilities.json'));
  // When the compiler-generated application manifest and capability are inspected.
  const app = manifests['__app-acl__'];
  const permissionSet = app.permission_sets['main-commands'];
  const resolved = permissionSet.permissions.flatMap(identifier => app.permissions[identifier].commands.allow).sort();
  // Then all 50 commands resolve through the main-only capability, without a default app grant.
  assert.deepEqual(resolved, commands);
  assert.equal(Object.keys(app.permissions).length, 100);
  assert.equal(app.default_permission, null);
  assert.deepEqual(capabilities.default.windows, ['main']);
  assert.deepEqual(capabilities.default.permissions, expectedPlugins);
  assert.deepEqual(capabilities['main-commands'].webviews, ['main']);
  assert.deepEqual(capabilities['main-commands'].windows ?? [], []);
  assert.deepEqual(capabilities['main-commands'].permissions, ['main-commands']);
  for (const command of commands) {
    const generated = read(`src-tauri/permissions/autogenerated/${command}.toml`);
    assert.ok(generated.includes(`commands.allow = ["${command}"]`));
    assert.ok(generated.includes(`commands.deny = ["${command}"]`));
  }
});
