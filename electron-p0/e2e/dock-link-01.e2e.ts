import {test,expect,_electron as electron} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {mkdir,mkdtemp,readFile,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

test('Dock links keep Workspace and school site separate in an isolated profile',async()=>{
  const root=await mkdtemp(join(tmpdir(),'bogunon-dock-link-'));
  const shots=join(process.cwd(),'artifacts','dock-link-01');await mkdir(shots,{recursive:true});
  const runId=randomUUID(),settingsDir=join(root,'test-runs',runId,'user-data','poc-settings');
  await mkdir(settingsDir,{recursive:true});
  await writeFile(join(settingsDir,'onboarding.json'),JSON.stringify({version:1,completed:true}));
  const launch=()=>electron.launch({chromiumSandbox:true,args:[join(process.cwd(),'build/electron-p0-app')],env:{...process.env,ELECTRON_P0_QA_PROFILE:'1',ELECTRON_P0_QA_ROOT:root,ELECTRON_P0_TEST_RUN:runId,ELECTRON_P0_DEV_URL:''}});
  let app=await launch();
  try{
    await expect.poll(()=>app.windows().filter(page=>page.url().includes('/palette/')).length).toBeGreaterThan(0);
    const palettes=app.windows().filter(page=>page.url().includes('/palette/'));
    await expect.poll(async()=>(await Promise.all(palettes.map(page=>page.locator('.palette-dock-region').isVisible()))).some(Boolean)).toBe(true);
    const visible=await Promise.all(palettes.map(page=>page.locator('.palette-dock-region').isVisible()));
    const activePalette=palettes[visible.indexOf(true)];
    const workspace=app.windows().find(page=>!page.url().includes('/palette/'));
    if(!activePalette||!workspace)throw Error('Workspace or Palette unavailable');
    await expect(activePalette.locator('[data-dock-item="online-health-room"]')).toHaveCount(0);
    await activePalette.screenshot({path:join(shots,'palette-online-off.png')});
    await activePalette.locator('[data-dock-item="bogunon"]').evaluate(button=>(button as HTMLElement).click());
    await expect.poll(()=>app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().filter(item=>item.isVisible()&&!item.webContents.getURL().includes('/palette/')).length)).toBe(1);
    await activePalette.locator('[data-dock-item="bogunon"]').evaluate(button=>(button as HTMLElement).click());
    expect(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().filter(item=>!item.webContents.getURL().includes('/palette/')).length)).toBe(1);
    await expect(workspace.getByRole('navigation',{name:'주요 기능'})).toBeVisible();
    await workspace.locator('.dock-zone [data-dock-item="settings"]').click();
    await expect(workspace.getByRole('dialog',{name:'설정',exact:true})).toBeVisible();
    await workspace.getByRole('button',{name:'온라인 보건실',exact:true}).click();
    const section=workspace.getByRole('region',{name:'온라인 보건실 설정'});
    await expect(section).toBeVisible();
    await section.getByRole('checkbox',{name:'온라인 보건실 사용'}).check();
    await section.getByRole('button',{name:'저장',exact:true}).click();
    await expect(section.getByRole('status')).toContainText('저장했습니다');
    expect(await workspace.evaluate(()=>window.electronP0.onlineHealthRoom.read())).toEqual({enabled:true,url:''});
    await workspace.getByRole('dialog',{name:'설정',exact:true}).getByRole('button',{name:'설정 닫기'}).click();
    await expect(activePalette.locator('[data-dock-item="online-health-room"]')).toHaveCount(1);
    await activePalette.screenshot({path:join(shots,'palette-online-on.png')});
    await activePalette.locator('[data-dock-item="online-health-room"]').evaluate(button=>(button as HTMLElement).click());
    await expect(workspace.getByRole('dialog',{name:'설정',exact:true})).toBeVisible();
    await expect(section).toBeVisible();
    await workspace.screenshot({path:join(shots,'online-health-room-settings.png')});
    await section.getByLabel('학교 온라인 보건실 URL').fill('https://health.school.edu.kr/room');
    await section.getByRole('button',{name:'저장',exact:true}).click();
    await expect(section.getByRole('status')).toContainText('저장했습니다');
    expect(JSON.parse(await readFile(join(settingsDir,'online-health-room.json'),'utf8'))).toEqual({enabled:true,url:'https://health.school.edu.kr/room'});
    await app.evaluate(({shell})=>{shell.openExternal=async(target:string)=>{(globalThis as typeof globalThis & {dockLinkOpened?:string}).dockLinkOpened=target;};});
    await workspace.getByRole('dialog',{name:'설정',exact:true}).getByRole('button',{name:'설정 닫기'}).click();
    await expect(activePalette.locator('[data-dock-item="online-health-room"]')).toHaveCount(1);
    await activePalette.locator('[data-dock-item="online-health-room"]').evaluate(button=>(button as HTMLElement).click());
    await expect.poll(()=>app.evaluate(()=> (globalThis as typeof globalThis & {dockLinkOpened?:string}).dockLinkOpened)).toBe('https://health.school.edu.kr/room');
    await app.evaluate(({shell})=>{shell.openExternal=async()=>{throw Error('Synthetic browser failure');};});
    await activePalette.locator('[data-dock-item="online-health-room"]').evaluate(button=>(button as HTMLElement).click());
    await expect(activePalette.getByRole('alert')).toContainText('주소와 기본 브라우저를 확인');
    await expect(activePalette.getByRole('main',{name:'BOGUNON DESK 바탕화면 위젯'})).toBeVisible();
    await workspace.locator('.dock-zone [data-dock-item="settings"]').click();
    await workspace.getByRole('button',{name:'온라인 보건실',exact:true}).click();
    await expect(section).toBeVisible();
    await section.getByLabel('학교 온라인 보건실 URL').fill('http://127.0.0.1/');
    await section.getByRole('button',{name:'저장',exact:true}).click();
    await expect(section.getByRole('status')).toContainText('HTTPS');
    expect(JSON.parse(await readFile(join(settingsDir,'online-health-room.json'),'utf8'))).toEqual({enabled:true,url:'https://health.school.edu.kr/room'});
    await section.getByLabel('학교 온라인 보건실 URL').fill('https://health.school.edu.kr/room');
    await section.getByRole('checkbox',{name:'온라인 보건실 사용'}).uncheck();
    await section.getByRole('button',{name:'저장',exact:true}).click();
    await workspace.getByRole('dialog',{name:'설정',exact:true}).getByRole('button',{name:'설정 닫기'}).click();
    await expect(activePalette.locator('[data-dock-item="online-health-room"]')).toHaveCount(0);
    await activePalette.screenshot({path:join(shots,'palette-online-off-saved.png')});
    await app.close();app=await launch();
    await expect.poll(async()=>{const pages=app.windows().filter(page=>page.url().includes('/palette/'));return (await Promise.all(pages.map(page=>page.locator('[data-dock-item="online-health-room"]').count()))).reduce((sum,count)=>sum+count,0);}).toBe(0);
    await expect.poll(()=>app.windows().some(page=>!page.url().includes('/palette/'))).toBe(true);
    const restarted=app.windows().find(page=>!page.url().includes('/palette/'));
    if(!restarted)throw Error('Restarted Workspace unavailable');
    expect(await restarted.evaluate(()=>window.electronP0.onlineHealthRoom.read())).toEqual({enabled:false,url:'https://health.school.edu.kr/room'});
  }finally{await app.close();}
});
