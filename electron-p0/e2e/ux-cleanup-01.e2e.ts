import {expect,test,_electron as electron} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {mkdir,mkdtemp,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

test('general-user Electron screens hide development controls',async()=>{
 const root=await mkdtemp(join(tmpdir(),'bogunon-ux-cleanup-'));
 const evidence=process.env.UX_CLEANUP_EVIDENCE;
 if(!evidence)throw Error('UX_CLEANUP_EVIDENCE is required');
 await mkdir(evidence,{recursive:true});
 const runId=randomUUID(),settings=join(root,'test-runs',runId,'user-data','poc-settings');
 await mkdir(settings,{recursive:true});
 await writeFile(join(settings,'onboarding.json'),JSON.stringify({version:1,completed:true}));
 const app=await electron.launch({chromiumSandbox:true,args:[join(process.cwd(),'build/electron-p0-app')],env:{...process.env,ELECTRON_P0_QA_PROFILE:'1',ELECTRON_P0_QA_ROOT:root,ELECTRON_P0_TEST_RUN:runId,ELECTRON_P0_DEV_URL:''}});
 try{
  await expect.poll(()=>app.windows().some(page=>page.url().includes('/palette/'))).toBe(true);
  const palette=app.windows().find(page=>page.url().includes('/palette/'));
  const workspace=app.windows().find(page=>!page.url().includes('/palette/'));
  if(!palette||!workspace)throw Error('Expected Palette and Workspace windows');
  await palette.locator('.palette-dock-region [data-dock-item="settings"]').evaluate(button=>(button as HTMLElement).click());
  const dialog=workspace.getByRole('dialog',{name:'설정',exact:true});
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button',{name:'앱 정보'}).click();
  await expect(dialog.getByRole('heading',{name:'앱 업데이트'})).toBeVisible();
  await expect(dialog.getByRole('button',{name:'합성 IPC 확인'})).toHaveCount(0);
  await workspace.screenshot({path:join(evidence,'app-info.png')});
  await dialog.getByRole('button',{name:'설정 닫기'}).click();
  await palette.locator('.palette-dock-region [data-dock-item="toolbox"]').evaluate(button=>(button as HTMLElement).click());
  await expect(palette.getByRole('region',{name:'업무 도구 선택'})).toBeVisible();
  await palette.getByRole('button',{name:'교육영상 Finder 열기'}).evaluate(button=>(button as HTMLElement).click());
  await expect(workspace.getByRole('heading',{name:'교육영상 찾기'})).toBeVisible();
  await expect(workspace.getByRole('option',{name:/Mock/})).toHaveCount(0);
  await workspace.screenshot({path:join(evidence,'finder.png')});
  await workspace.getByRole('button',{name:'보건 업무로'}).click();
  await palette.locator('.palette-dock-region [data-dock-item="toolbox"]').evaluate(button=>(button as HTMLElement).click());
  await expect(palette.getByRole('button',{name:'물품 관리 열기'})).toBeVisible();
  await palette.getByRole('button',{name:'물품 관리 열기'}).evaluate(button=>(button as HTMLElement).click());
  await expect(workspace.getByRole('heading',{name:'재고 관리'})).toBeVisible();
  await expect(workspace.getByText(/preview_only|persisted:false/)).toHaveCount(0);
  await workspace.screenshot({path:join(evidence,'inventory.png')});
  await workspace.getByRole('button',{name:'대시보드로'}).click();
  await palette.locator('.palette-dock-region [data-dock-item="bogunon"]').evaluate(button=>(button as HTMLElement).click());
  await expect(workspace.getByRole('navigation',{name:'주요 기능'})).toBeVisible();
  await workspace.getByRole('navigation',{name:'주요 기능'}).getByRole('button',{name:'업무 도구'}).click();
  await expect(workspace.getByRole('button',{name:'학교 행정 도우미'})).toBeVisible();
  await workspace.getByRole('button',{name:'학교 행정 도우미'}).click();
  await expect(workspace.getByRole('heading',{name:'학교 업무 바로가기'})).toBeVisible();
  await expect(workspace.getByText(/FIELD_VERIFIED|UNVERIFIED/)).toHaveCount(0);
  await workspace.screenshot({path:join(evidence,'smart-work-launcher.png')});
  await workspace.getByRole('button',{name:'보건 업무로'}).click();
  await palette.locator('.palette-dock-region [data-dock-item="toolbox"]').evaluate(button=>(button as HTMLElement).click());
  await palette.getByRole('button',{name:'보건소식지 제작소 열기'}).evaluate(button=>(button as HTMLElement).click());
  await expect(workspace.getByRole('region',{name:'보건소식지 제작소'})).toBeVisible();
  await workspace.screenshot({path:join(evidence,'newsletter.png')});
  await workspace.getByRole('button',{name:'새 소식지 작성'}).click();
  await workspace.getByLabel('작성 월').fill('2026-11');
  await workspace.getByRole('button',{name:'새 소식지 만들기'}).click();
  await expect(workspace.getByRole('heading',{name:'보건소식지 디자인 편집기'})).toBeVisible();
  await workspace.screenshot({path:join(evidence,'newsletter-preview.png'),fullPage:true});
 }finally{await app.close();}
});
